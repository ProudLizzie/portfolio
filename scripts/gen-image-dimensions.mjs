// Generates lib/image-dimensions.ts: a map of every image in /public to its
// intrinsic { width, height }. This lets NaturalImage reserve the correct
// aspect-ratio box so images are never cropped, squished, or collapsed while
// lazy-loading. Re-run this whenever images are added or replaced:
//   node scripts/gen-image-dimensions.mjs
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { imageSize } from 'image-size'

const PUBLIC_DIR = join(process.cwd(), 'public')
const OUT_FILE = join(process.cwd(), 'lib', 'image-dimensions.ts')
const EXTS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.webp', '.avif', '.svg'])

/** @param {string} dir */
function walk(dir) {
  /** @type {string[]} */
  const files = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      files.push(...walk(full))
    } else {
      const lower = entry.toLowerCase()
      if ([...EXTS].some((ext) => lower.endsWith(ext))) files.push(full)
    }
  }
  return files
}

const map = {}
for (const file of walk(PUBLIC_DIR)) {
  try {
    const { width, height } = imageSize(readFileSync(file))
    if (!width || !height) continue
    // Web path relative to /public, always forward-slashed and root-anchored.
    const webPath = '/' + relative(PUBLIC_DIR, file).split(/[\\/]/).join('/')
    map[webPath] = { width, height }
  } catch {
    // Skip anything image-size can't parse.
  }
}

const sorted = Object.keys(map)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: { width: ${map[k].width}, height: ${map[k].height} },`)
  .join('\n')

const contents = `// AUTO-GENERATED by scripts/gen-image-dimensions.mjs. Do not edit by hand.
// Intrinsic pixel dimensions for every image in /public, used to preserve
// natural aspect ratios without cropping.
export const imageDimensions: Record<string, { width: number; height: number }> = {
${sorted}
}
`

writeFileSync(OUT_FILE, contents)
console.log(`Wrote ${Object.keys(map).length} image dimensions to ${OUT_FILE}`)
